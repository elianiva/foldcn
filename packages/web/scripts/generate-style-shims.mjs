/**
 * generate-style-shims.mjs — emit per-item re-export modules that expose the
 * ACTIVE registry style's resolved tree (see src/active-style.ts) through
 * ES-module live bindings, so the demo can switch styles instantly.
 *
 * Why shims exist: the nine style trees are fully-resolved module graphs —
 * the same authored sources with different class strings baked in — so a
 * style switch means rebinding which tree's exports the demo reads. Each shim
 * declares `export let <name>` for every value export (initialized from the
 * default tree so types stay exact) and reassigns them when
 * `setActiveStyle()` fires the registered reloader. Because consumers read
 * these bindings inside view functions, the foldkit re-render after a style
 * message picks up the new classes with no reload — demo state (open
 * accordions, dialog state, toasts) is preserved.
 *
 * Generated output: src/generated/registry/{ui,lib,blocks}/<item>.ts
 * Run automatically by the web package's predev/prebuild/pretypecheck/pretest
 * hooks, after resolve-styles.mjs has produced the trees.
 */
import { mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const WEB_DIR = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const OUT_ROOT = join(WEB_DIR, 'src', 'generated', 'registry')
const TREES = resolve(WEB_DIR, '../registry/styles')
const STYLES = ['default', 'nova', 'vega', 'maia', 'lyra', 'mira', 'luma', 'sera', 'rhea']

/** Relative subpaths (from the resolved-tree root) of every shipped item. */
const itemPaths = () => {
  const paths = []
  for (const group of ['ui', 'lib']) {
    for (const file of readdirSync(join(TREES, 'default', group))) {
      if (file.endsWith('.ts')) paths.push(`${group}/${file}`)
    }
  }
  const blocksDir = join(TREES, 'default', 'blocks')
  for (const block of readdirSync(blocksDir)) {
    for (const file of readdirSync(join(blocksDir, block))) {
      if (file.endsWith('.ts')) paths.push(`blocks/${block}/${file}`)
    }
  }
  return paths.sort()
}

const valueExports = (source) => {
  const names = []
  for (const match of source.matchAll(
    /^export (?:const|function|async function|let|var) ([A-Za-z_$][\w$]*)/gm,
  )) {
    names.push(match[1])
  }
  for (const match of source.matchAll(/^export\s*\{([^}]+)\}/gm)) {
    for (const part of match[1].split(',')) {
      const trimmed = part.trim()
      if (!trimmed || trimmed.startsWith('type ')) continue
      const alias = trimmed.split(/\s+as\s+/)[1] ?? trimmed.split(/\s+/)[0]
      if (alias) names.push(alias.trim())
    }
  }
  return names
}

const typeExports = (source) => {
  const names = []
  for (const match of source.matchAll(/^export type ([A-Za-z_$][\w$]*)/gm)) {
    names.push(match[1])
  }
  return names
}

const generate = () => {
  // Parity check first: shims assume identical export surfaces across styles.
  for (const relPath of itemPaths()) {
    const source = readFileSync(join(TREES, 'default', relPath), 'utf8')
    const reference = [...valueExports(source), ...typeExports(source)].sort((a, b) =>
      a.localeCompare(b),
    )
    for (const style of STYLES.slice(1)) {
      const otherSource = readFileSync(join(TREES, style, relPath), 'utf8')
      const other = [...valueExports(otherSource), ...typeExports(otherSource)].sort((a, b) =>
        a.localeCompare(b),
      )
      if (reference.length !== other.length || reference.some((name, i) => name !== other[i])) {
        throw new Error(`export mismatch between default and ${style} for ${relPath}`)
      }
    }
  }

  rmSync(OUT_ROOT, { recursive: true, force: true })

  let count = 0
  for (const relPath of itemPaths()) {
    const source = readFileSync(join(TREES, 'default', relPath), 'utf8')
    const values = valueExports(source)
    const types = typeExports(source)
    if (values.length === 0 && types.length === 0) continue

    // src/generated/registry/<rel> → src/: the item's own file name counts as
    // a segment too, hence +1 over its directory depth.
    const depth = '../'.repeat(relPath.split('/').length + 1)
    const moduleSpecifier = (style) =>
      `@foldcn/registry/styles/${style}/${relPath.replace(/\.ts$/, '')}`
    const importSpecifiers = STYLES.map(
      (style) => `import * as _${style.replace(/-/g, '_')} from '${moduleSpecifier(style)}'`,
    )

    const lines = [
      '// Generated by scripts/generate-style-shims.mjs — do not edit.',
      `// Live-binding re-exports of the active registry style (${STYLES.join(', ')}) — see src/active-style.ts.`,
      ...importSpecifiers,
      `import { activeRegistryStyle, registerStyleReloader } from '${depth}active-style'`,
      '',
      'const __trees = {',
      ...STYLES.map((style) => `  ${style.replace(/-/g, '_')}: _${style.replace(/-/g, '_')},`),
      '} as const',
      '',
      `// The tree active at module-evaluation time (the stored preference on`,
      '// the client, always default on the server). The cast keeps the',
      '// exported types exact — the generator asserts identical export',
      '// surfaces across all trees.',
      'const __initial = __trees[activeRegistryStyle()] as typeof _default',
      '',
      '// Live bindings: reassigned to the active tree on every style switch.',
      '// Consumers read them inside view functions, so the post-switch',
      '// re-render is instant and preserves demo state.',
      ...values.map((name) => `export let ${name} = __initial.${name}`),
      '',
    ]

    // Types split two ways. Pure types (incl. generic Config types) use an
    // `export type { … } from` re-export, which carries type parameters
    // intact. Names that are ALSO value exports (Schema structs like
    // Model/Message) need a local alias so namespace consumers can use them in
    // type position too — these are never generic, and a local `export type X`
    // happily merges with the `export let X` binding.
    const aliasedTypes = []
    const pureTypes = []
    for (const name of types) {
      if (values.includes(name)) {
        aliasedTypes.push(`export type ${name} = _default.${name}`)
      } else {
        pureTypes.push(name)
      }
    }
    if (pureTypes.length > 0) {
      lines.push(
        `export type {\n  ${pureTypes.join(',\n  ')},\n} from '${moduleSpecifier('default')}'`,
      )
    }
    lines.push(...aliasedTypes)

    lines.push(
      '',
      '// Rebinds every export to the active tree. The namespace cast is safe:',
      '// the generator asserts identical export surfaces across all trees.',
      'const __rebind = (): void => {',
      '  const __t = __trees[activeRegistryStyle()] as typeof _default',
      ...values.map((name) => `  ${name} = __t.${name}`),
      '}',
      '',
      'registerStyleReloader(__rebind)',
      '',
    )

    const outPath = join(OUT_ROOT, relPath)
    mkdirSync(dirname(outPath), { recursive: true })
    writeFileSync(outPath, lines.join('\n'))
    count += 1
  }
  console.log(`generate-style-shims: wrote ${count} shim(s) → ${OUT_ROOT}`)
}

generate()
